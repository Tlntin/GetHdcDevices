const DICTS: Record<Lang, Dict> = { en, "zh-CN": zhCN, "zh-HK": zhHK };

let current: Lang = "en";

/** Detect the best-matching supported language from the system, default English. */
export function detectLang(): Lang {
  const cands =
    navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || ""];
  for (const raw of cands) {
    const l = String(raw).toLowerCase();
    if (l.startsWith("zh")) {
      // Traditional regions/scripts → Hong Kong Traditional; otherwise Simplified.
      return /hk|tw|mo|hant/.test(l) ? "zh-HK" : "zh-CN";
    }
    if (l.startsWith("en")) return "en";
  }
  return "en";
}

export function isLang(v: unknown): v is Lang {
  return v === "en" || v === "zh-CN" || v === "zh-HK";
}

export function getLang(): Lang {
  return current;
}

export function setLang(l: Lang) {
  current = isLang(l) ? l : "en";
}

/** Translate `key`, interpolating `{name}` placeholders from `params`. */
export function t(key: string, params?: Record<string, string | number>): string {
  const dict = DICTS[current] || en;
  let s = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/**
 * Apply translations to all static markup under `root`:
 *  - `data-i18n`        → textContent
 *  - `data-i18n-html`   → innerHTML (for strings containing markup)
 *  - `data-i18n-ph`     → placeholder
 *  - `data-i18n-title`  → title
 */
export function applyStaticTranslations(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n!);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml!);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-ph]").forEach((el) => {
    (el as HTMLInputElement).placeholder = t(el.dataset.i18nPh!);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle!);
  });
  document.title = t("app.title");
  document.documentElement.lang = current;
}
